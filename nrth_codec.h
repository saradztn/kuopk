#ifndef NRTH_AUDIT_H
static inline void NrthXorTransform(const uint8_t *in, size_t len, uint8_t key, uint8_t *out)
{
    for (size_t p = 0; p < len; ++p)
        out[p] = (uint8_t)(in[p] ^ (uint8_t)(p - key));
}
#endif

static inline void NrthXorCodecBuf(const uint8_t *in, size_t len, uint8_t key, uint8_t *out)
{
    for (size_t p = 0; p < len; ++p)
        out[p] = (uint8_t)(in[p] ^ (uint8_t)(p - key));
}

/**
 * Single-use gate decryptor (matches original NRTH.dll decryptor pattern):
 *   Given a ciphertext buffer of field size F (`fieldSize`), key K (`key`),
 *   mutable plaintext buffer `plainBuf` (>= F bytes), and boolean `*gate`:
 *   On first invocation (`!*gate`), decodes L = F - 1 bytes, writes NUL at
 *   `plainBuf[L]`, and flips `*gate = true`. Subsequent calls return `plainBuf`
 *   immediately without re-running the loop.
 */
static inline const char *NrthDecryptOnce(const uint8_t *cipher, size_t fieldSize,
                                          uint8_t key, char *plainBuf, bool *gate)
{
    if (!cipher || !plainBuf || fieldSize == 0) {
        return "";
    }
    size_t L = fieldSize - 1;
    if (!gate || !*gate) {
        for (size_t p = 0; p < L; ++p) {
            plainBuf[p] = (char)(cipher[p] ^ (uint8_t)(p - key));
        }
        plainBuf[L] = '\0';
        if (gate) {
            *gate = true;
        }
    }
    return plainBuf;
}

